"""The decorative rowboat (prop `barque_deco`): an exact copy of the sailing rowboat's model (models/entity/rowboat.bbmodel,
generated by tools/generate_rowboat.py) as a one-block static prop, like the carts: the copy is lifted so that the keel
rests on the ground (the sailing boat's model has its waterline at y = 0 and its keel 0.44 below), its animation dropped
(nothing moves), plus the prop JSON (carts/barque_deco.json): the rowboat's texture, the hull's collision boxes (bow,
middle, stern; the oars do not collide) and the two thwarts as seats (the rower's and the passenger's, facing the bow).
Run it again after regenerating the rowboat to keep both boats identical.
Coordinates: prop-local blocks, y up (0 = top of the ground block), +z = the bow (it points towards the player who
places the boat), the anchor block's centre at (0, 0, 0).
"""
import copy
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "..", "src", "main", "resources", "assets", "medievalships")
SRC = os.path.join(ASSETS, "models", "entity", "rowboat.bbmodel")
OUT_MODEL = os.path.join(ASSETS, "models", "entity", "barque_deco.bbmodel")
OUT_JSON = os.path.join(ASSETS, "carts", "barque_deco.json")

# the rowboat's layout (core/RowboatLayout.java): thwart tops and positions, rail height, half width
THWART_TOP = 0.62
PILOT_Z, PASSENGER_Z = 0.05, -1.15
RAIL_BASE = 0.78


def main():
    m = json.load(open(SRC))
    ymin = min(min(e["from"][1], e["to"][1]) for e in m["elements"] if e.get("type", "cube") == "cube") / 16.0
    dy = -ymin  # the keel's bottom on the ground
    d = dy * 16.0
    out = copy.deepcopy(m)
    out["name"] = "barque_deco"
    out["animations"] = []
    for e in out["elements"]:
        for k in ("from", "to", "origin"):
            if k in e:
                e[k][1] += d

    def lift(node):
        if isinstance(node, dict):
            if "origin" in node:
                node["origin"][1] += d
            for c in node.get("children", []):
                lift(c)
    for n in out["outliner"]:
        lift(n)
    for g in out.get("groups", []):
        if "origin" in g:
            g["origin"][1] += d
    with open(OUT_MODEL, "w") as f:
        json.dump(out, f, separators=(",", ":"))

    cubes = [e for e in out["elements"] if e.get("type", "cube") == "cube"]
    lo = [min(min(e["from"][i], e["to"][i]) for e in cubes) / 16.0 for i in range(3)]
    hi = [max(max(e["from"][i], e["to"][i]) for e in cubes) / 16.0 for i in range(3)]
    pad = 0.05
    extent = [round(lo[0] - pad, 3), 0.0, round(lo[2] - pad, 3), round(hi[0] + pad, 3), round(hi[1] + pad, 3), round(hi[2] + pad, 3)]
    rail = RAIL_BASE + dy
    colliders = [
        [-0.95, 0.0, -1.6, 0.95, round(rail, 3), 1.6],          # the middle of the hull, up to the gunwales
        [-0.6, 0.0, 1.6, 0.6, round(rail + 0.1, 3), 2.55],      # the bow
        [-0.6, 0.0, -2.55, 0.6, round(rail + 0.08, 3), -1.6],   # the stern
    ]
    seats = [
        {"pos": [0.0, round(THWART_TOP + dy, 3), PILOT_Z], "yaw": 0.0},
        {"pos": [0.0, round(THWART_TOP + dy, 3), PASSENGER_Z], "yaw": 0.0},
    ]
    data = {"model": "models/entity/barque_deco.bbmodel", "texture": "textures/entity/rowboat.png", "decor": None,
            "extent": extent, "colliders": colliders, "seats": seats}
    with open(OUT_JSON, "w") as f:
        json.dump(data, f, indent=1)
    print("barque_deco: %d cubes, lifted %.3f, extent %s" % (len(cubes), dy, extent))


if __name__ == "__main__":
    main()
