    rows = []
    for z in (-27.3, -22.0, -14.0, -5.0, 0.0, 9.0, 20.0, 26.0):
        rows.append("\t\t\t{%s, %.6f, %.6f, %.6f, %.6f}" % (z, half_width(z), rail_y(z), keel_y(z), bottom_y(z, 2.0)))
    java = ("package fr.medievalships.core;\n\n"
            "/** Generated by tools/warship_shape.py: hull values (z, half width, rail, keel, bottom at 2 blocks). */\n"
            "final class WarshipShapeReference {\n"
            "\tstatic final double[][] VALUES = {\n" + ",\n".join(rows) + "};\n\n"
            "\tprivate WarshipShapeReference() {\n\t}\n}\n")
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    with open(os.path.join(root, "src/test/java/fr/medievalships/core/WarshipShapeReference.java"), "w") as f:
        f.write(java)
    print(java)
