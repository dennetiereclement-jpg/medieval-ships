"""Hull shape and layout of the great warship, shared by the model generator.

MUST stay identical to fr.medievalships.core.HullShape + Ships.warship() (Java), which
use the same formulas and numbers for collisions, seats and terrain probes (checked by
WarshipTest.hullMatchesModelGenerator; `python3 tools/warship_shape.py` rewrites the
reference values).

Ship-local coordinates, in blocks:
  x = lateral (+x = port / babord), y = up (0 = model origin, the water is at WATERLINE_Y), z = forward (+z = bow).
"""
import os

HALF_LENGTH = 27.5
TIP = 28.6
MAX_HALF_WIDTH = 6.5
FORE_SCALE, FORE_POW_A, FORE_POW_B = 28.4, 2.2, 0.55
AFT_SCALE, AFT_POW_A, AFT_POW_B = 30.5, 3.2, 0.45
KEEL_DEPTH, KEEL_RISE, KEEL_POW = 2.9, 2.2, 3.5
WATERLINE_Y = -1.1  # water surface under the model origin when afloat (the hull floats high)
RAIL_BASE, RAIL_RISE_FORE, RAIL_RISE_AFT, RAIL_POW = 5.8, 1.8, 2.0, 2.5
BOTTOM_SECTION = [(0.0, 1.0), (0.5, 0.9), (0.82, 0.55), (0.97, 0.12)]

MAIN_DECK_Y = 4.5
FORECASTLE_Y = 6.8
FORECASTLE_START = 17.0
QUARTERDECK_Y = 7.1
QUARTERDECK_START = -10.0
POOP_Y = 9.4
POOP_START = -19.0
SLAB = 0.3
BULKHEAD_THICK = 0.3
DOOR_HALF = 0.8
DOOR_TOP = 6.55
TRANSOM_Z = -27.3
DECK_MAX_Z = 27.0
FORE_MAST_Z, FORE_MAST_TOP = 17.5, 34.0
MAIN_MAST_Z, MAIN_MAST_TOP = 1.0, 40.5
MIZZEN_Z, MIZZEN_TOP = -14.5, 30.0
HELM_Z = -11.2
PILOT_Z = -12.0
QD_STAIR_X0, QD_STAIR_X1, QD_STAIR_START = 2.4, 4.4, -7.5
POOP_STAIR_X0, POOP_STAIR_X1, POOP_STAIR_START = 2.4, 4.0, -16.5
FC_STAIR_X0, FC_STAIR_X1, FC_STAIR_START = 1.8, 3.4, 14.5
STEP_DEPTH = 0.5
RAIL_HEIGHT = 0.9
RAIL_THICK = 0.12
CARRIAGE_Z = [-7.0, -3.5, 0.0, 3.5, 7.0, 10.5]
CARRIAGE_TOP = MAIN_DECK_Y + 0.6
LOWER_GUN_Y = 1.5
MIDDLE_GUN_Y = 3.2
MAIN_GUN_Y = MAIN_DECK_Y + 0.9
LOWER_GUNS = 12
MIDDLE_GUNS = 11
GUN_Z0, GUN_Z1 = -20.0, 18.5
QD_RAIL_Y = QUARTERDECK_Y + 1.0
POOP_RAIL_Y = POOP_Y + 1.0
FC_RAIL_Y = FORECASTLE_Y + 1.0


BAND_LIFT = 0.7
BOAT_Z0, BOAT_Z1, BOAT_HALF = 4.6, 11.6, 1.15
BOAT_TOP = MAIN_DECK_Y + 1.5


def band_lift(z):
    """Hull bands and gun rows rise towards the ends, parallel to the sheer."""
    a = abs(z) / HALF_LENGTH
    rise = RAIL_RISE_FORE if z >= 0 else RAIL_RISE_AFT
    return BAND_LIFT * rise * a ** RAIL_POW


def gun_z(k, n):
    return GUN_Z0 + (GUN_Z1 - GUN_Z0) * (k + 0.5) / n


def half_width(z):
    fore = z >= 0
    a = abs(z) / (FORE_SCALE if fore else AFT_SCALE)
    if a >= 1.0:
        return 0.0
    pa, pb = (FORE_POW_A, FORE_POW_B) if fore else (AFT_POW_A, AFT_POW_B)
    return MAX_HALF_WIDTH * (1.0 - a ** pa) ** pb


def deck_y(z):
    return FORECASTLE_Y if z > FORECASTLE_START else MAIN_DECK_Y


def sheer_y(z):
    a = abs(z) / HALF_LENGTH
    rise = RAIL_RISE_FORE if z >= 0 else RAIL_RISE_AFT
    return RAIL_BASE + rise * a ** RAIL_POW


def rail_y(z):
    y = sheer_y(z)
    if z < POOP_START:
        y = max(y, POOP_RAIL_Y)
    if z < QUARTERDECK_START:
        y = max(y, QD_RAIL_Y)
    if z > FORECASTLE_START:
        y = max(y, FC_RAIL_Y)
    return y


def keel_y(z):
    a = abs(z) / HALF_LENGTH
    return -KEEL_DEPTH + KEEL_RISE * a ** KEEL_POW


def inner_half_width(z):
    return max(0.0, 0.97 * half_width(z) - 0.12)


def bottom_y(z, ax):
    w, yk = half_width(z), keel_y(z)
    if w <= 0.1:
        return yk
    s = BOTTOM_SECTION
    if ax >= s[-1][0] * w:
        return s[-1][1] * yk
    for i in range(len(s) - 1):
        x0, x1 = s[i][0] * w, s[i + 1][0] * w
        if ax <= x1:
            f = (ax - x0) / (x1 - x0)
            return s[i][1] * yk + (s[i + 1][1] - s[i][1]) * yk * f
    return s[-1][1] * yk


